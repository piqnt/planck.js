// Writes docs/pages/examples.md, generated so it cannot drift from what the build publishes.
//
// The links are raw HTML and absolute on purpose: a markdown link would get the docs' base
// prepended, and a relative one would turn on whether the url kept its trailing slash. They take
// the site's base, so a preview deployment at another path still points at its own examples.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

import { exampleNames } from "./examples-list.mjs";
import { SITE_BASE } from "./vite-shared.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs", "pages", "examples.md");

const names = exampleNames();

const page = `---
# generated by scripts/examples-doc-page.mjs — edit that, not this
title: Examples
---

# Examples

Every example runs on its own page, with the testbed's playlist, toolbar and outline around it,
built from the sources in
[\`example/\`](https://github.com/piqnt/planck.js/tree/master/example). Each page links to the file
it came from — clone the repo and run \`npm install && npm run dev\` to change it and see the
result straight away.

<div class="example-list">
${names.map((name) => `<a href="${SITE_BASE}${name}" target="_self">${name}</a>`).join("\n")}
</div>

<style>
.example-list {
  display: grid;
  grid-template-columns: repeat(auto-fill, minmax(11rem, 1fr));
  gap: 0.5rem 1rem;
  margin-top: 1.5rem;
}
.example-list a {
  font-weight: 500;
}
</style>
`;

fs.writeFileSync(OUT, page);
console.log(`examples.md: ${names.length} examples`);
